BEGIN;

DROP TABLE IF EXISTS return_request          CASCADE;
DROP TABLE IF EXISTS review                  CASCADE;
DROP TABLE IF EXISTS stock_movement          CASCADE;
DROP TABLE IF EXISTS stock_level             CASCADE;
DROP TABLE IF EXISTS shipment_line           CASCADE;
DROP TABLE IF EXISTS shipment                CASCADE;
DROP TABLE IF EXISTS payment                 CASCADE;
DROP TABLE IF EXISTS order_promotion         CASCADE;
DROP TABLE IF EXISTS order_line              CASCADE;
DROP TABLE IF EXISTS customer_order          CASCADE;
DROP TABLE IF EXISTS promotion               CASCADE;
DROP TABLE IF EXISTS cart_item               CASCADE;
DROP TABLE IF EXISTS cart                    CASCADE;
DROP TABLE IF EXISTS customer_address        CASCADE;
DROP TABLE IF EXISTS customer                CASCADE;
DROP TABLE IF EXISTS product_supplier        CASCADE;
DROP TABLE IF EXISTS supplier                CASCADE;
DROP TABLE IF EXISTS warehouse               CASCADE;
DROP TABLE IF EXISTS variant_attribute_value CASCADE;
DROP TABLE IF EXISTS product_variant         CASCADE;
DROP TABLE IF EXISTS attribute_value         CASCADE;
DROP TABLE IF EXISTS attribute               CASCADE;
DROP TABLE IF EXISTS product_category        CASCADE;
DROP TABLE IF EXISTS product                 CASCADE;
DROP TABLE IF EXISTS category                CASCADE;
DROP TABLE IF EXISTS brand                   CASCADE;


-- -----------------------------------------------------------------------------
-- 1. Catalogue: brand, category, product, product_variant
-- -----------------------------------------------------------------------------

CREATE TABLE brand (
    brand_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(80) NOT NULL,
    CONSTRAINT uq_brand_name UNIQUE (name)
);

-- Self-referencing hierarchy: Electronics > Phones > Android.
-- parent_category_id is NULL for root categories.
CREATE TABLE category (
    category_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_category_id INTEGER REFERENCES category (category_id) ON DELETE RESTRICT,
    name               VARCHAR(80) NOT NULL,
    slug               VARCHAR(80) NOT NULL,
    CONSTRAINT uq_category_slug UNIQUE (slug),
    CONSTRAINT ck_category_not_own_parent CHECK (parent_category_id <> category_id)
);

-- The marketing item. Price and stock live on product_variant, not here.
CREATE TABLE product (
    product_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200) NOT NULL,
    description TEXT,
    brand_id    INTEGER NOT NULL REFERENCES brand (brand_id) ON DELETE RESTRICT,
    status      VARCHAR(16) NOT NULL DEFAULT 'active',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_product_status CHECK (status IN ('active', 'discontinued', 'draft'))
);

-- M:N: a product may be cross-listed in more than one leaf category.
CREATE TABLE product_category (
    product_id  INTEGER NOT NULL REFERENCES product (product_id) ON DELETE CASCADE,
    category_id INTEGER NOT NULL REFERENCES category (category_id) ON DELETE RESTRICT,
    PRIMARY KEY (product_id, category_id)
);

-- Arbitrary attribute types (colour, size, capacity, ...) held as data rather
-- than as columns, so new attribute types need no schema change (1NF).
CREATE TABLE attribute (
    attribute_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(40) NOT NULL,
    CONSTRAINT uq_attribute_name UNIQUE (name)
);

CREATE TABLE attribute_value (
    value_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribute_id INTEGER NOT NULL REFERENCES attribute (attribute_id) ON DELETE CASCADE,
    value        VARCHAR(60) NOT NULL,
    CONSTRAINT uq_attribute_value UNIQUE (attribute_id, value)
);

-- The sellable item. SKU-level price and identifiers belong here.
CREATE TABLE product_variant (
    variant_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES product (product_id) ON DELETE CASCADE,
    sku        VARCHAR(40) NOT NULL,
    price      NUMERIC(12, 2) NOT NULL,
    weight_g   INTEGER,
    status     VARCHAR(16) NOT NULL DEFAULT 'active',
    CONSTRAINT uq_variant_sku UNIQUE (sku),
    CONSTRAINT ck_variant_price CHECK (price > 0),
    CONSTRAINT ck_variant_weight CHECK (weight_g IS NULL OR weight_g > 0),
    CONSTRAINT ck_variant_status CHECK (status IN ('active', 'discontinued'))
);

-- M:N: a variant has a colour value AND a size/capacity value.
CREATE TABLE variant_attribute_value (
    variant_id INTEGER NOT NULL REFERENCES product_variant (variant_id) ON DELETE CASCADE,
    value_id   INTEGER NOT NULL REFERENCES attribute_value (value_id) ON DELETE RESTRICT,
    PRIMARY KEY (variant_id, value_id)
);


-- -----------------------------------------------------------------------------
-- 2. Supply and stock
-- -----------------------------------------------------------------------------

CREATE TABLE warehouse (
    warehouse_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(80) NOT NULL,
    city         VARCHAR(80) NOT NULL,
    country      CHAR(2) NOT NULL,
    region       VARCHAR(40) NOT NULL,
    CONSTRAINT uq_warehouse_name UNIQUE (name)
);

CREATE TABLE supplier (
    supplier_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    country     CHAR(2) NOT NULL,
    CONSTRAINT uq_supplier_name UNIQUE (name)
);

CREATE TABLE product_supplier (
    product_id     INTEGER NOT NULL REFERENCES product (product_id) ON DELETE CASCADE,
    supplier_id    INTEGER NOT NULL REFERENCES supplier (supplier_id) ON DELETE RESTRICT,
    unit_cost      NUMERIC(12, 2) NOT NULL,
    lead_time_days INTEGER NOT NULL,
    is_primary     BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (product_id, supplier_id),
    CONSTRAINT ck_ps_cost CHECK (unit_cost > 0),
    CONSTRAINT ck_ps_lead CHECK (lead_time_days >= 0)
);

-- Quantity on hand per warehouse. Composite key: the quantity depends on the
-- variant AND the warehouse, never on either alone (2NF).
CREATE TABLE stock_level (
    variant_id    INTEGER NOT NULL REFERENCES product_variant (variant_id) ON DELETE CASCADE,
    warehouse_id  INTEGER NOT NULL REFERENCES warehouse (warehouse_id) ON DELETE RESTRICT,
    quantity      INTEGER NOT NULL DEFAULT 0,
    reorder_point INTEGER NOT NULL DEFAULT 0,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (variant_id, warehouse_id),
    CONSTRAINT ck_stock_quantity CHECK (quantity >= 0),
    CONSTRAINT ck_stock_reorder CHECK (reorder_point >= 0)
);


-- -----------------------------------------------------------------------------
-- 3. Customers
-- -----------------------------------------------------------------------------

CREATE TABLE customer (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(160) NOT NULL,
    first_name  VARCHAR(60) NOT NULL,
    last_name   VARCHAR(60) NOT NULL,
    phone       VARCHAR(30),
    status      VARCHAR(16) NOT NULL DEFAULT 'active',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_customer_email UNIQUE (email),
    CONSTRAINT ck_customer_status CHECK (status IN ('active', 'suspended', 'closed'))
);

CREATE TABLE customer_address (
    address_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customer (customer_id) ON DELETE CASCADE,
    line1       VARCHAR(120) NOT NULL,
    line2       VARCHAR(120),
    city        VARCHAR(80) NOT NULL,
    region      VARCHAR(80),
    postcode    VARCHAR(20) NOT NULL,
    country     CHAR(2) NOT NULL,
    is_default  BOOLEAN NOT NULL DEFAULT FALSE
);

-- At most one default address per customer (partial unique index).
CREATE UNIQUE INDEX ux_customer_default_address
    ON customer_address (customer_id)
    WHERE is_default;


-- -----------------------------------------------------------------------------
-- 4. Cart and promotions
-- -----------------------------------------------------------------------------

CREATE TABLE cart (
    cart_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customer (customer_id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    status      VARCHAR(16) NOT NULL DEFAULT 'open',
    CONSTRAINT ck_cart_status CHECK (status IN ('open', 'converted', 'abandoned'))
);

CREATE TABLE cart_item (
    cart_id    INTEGER NOT NULL REFERENCES cart (cart_id) ON DELETE CASCADE,
    variant_id INTEGER NOT NULL REFERENCES product_variant (variant_id) ON DELETE CASCADE,
    quantity   INTEGER NOT NULL,
    PRIMARY KEY (cart_id, variant_id),
    CONSTRAINT ck_cart_item_qty CHECK (quantity > 0)
);

CREATE TABLE promotion (
    promotion_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(30) NOT NULL,
    description    VARCHAR(160),
    discount_type  VARCHAR(12) NOT NULL,
    discount_value NUMERIC(10, 2) NOT NULL,
    min_spend      NUMERIC(12, 2) NOT NULL DEFAULT 0,
    starts_at      TIMESTAMPTZ NOT NULL,
    ends_at        TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_promotion_code UNIQUE (code),
    CONSTRAINT ck_promotion_type CHECK (discount_type IN ('percent', 'fixed')),
    CONSTRAINT ck_promotion_value CHECK (discount_value > 0),
    CONSTRAINT ck_promotion_window CHECK (ends_at > starts_at)
);


-- -----------------------------------------------------------------------------
-- 5. Orders
-- -----------------------------------------------------------------------------

CREATE TABLE customer_order (
    order_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id         INTEGER NOT NULL REFERENCES customer (customer_id) ON DELETE RESTRICT,
    order_date          TIMESTAMPTZ NOT NULL,
    status              VARCHAR(16) NOT NULL,
    shipping_address_id INTEGER NOT NULL REFERENCES customer_address (address_id) ON DELETE RESTRICT,
    billing_address_id  INTEGER NOT NULL REFERENCES customer_address (address_id) ON DELETE RESTRICT,
    currency            CHAR(3) NOT NULL DEFAULT 'GBP',
    subtotal            NUMERIC(12, 2) NOT NULL,
    discount_total      NUMERIC(12, 2) NOT NULL DEFAULT 0,
    shipping_total      NUMERIC(12, 2) NOT NULL DEFAULT 0,
    tax_total           NUMERIC(12, 2) NOT NULL DEFAULT 0,
    grand_total         NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_order_status CHECK (
        status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled', 'refunded')
    ),
    CONSTRAINT ck_order_money CHECK (
        subtotal >= 0 AND discount_total >= 0 AND shipping_total >= 0
        AND tax_total >= 0 AND grand_total >= 0
    ),
    CONSTRAINT ck_order_discount_cap CHECK (discount_total <= subtotal)
);

-- unit_price is a deliberate, non-redundant snapshot of the variant price at
-- the moment of sale. Variant prices change over time; invoices must not.
CREATE TABLE order_line (
    order_id   INTEGER NOT NULL REFERENCES customer_order (order_id) ON DELETE CASCADE,
    variant_id INTEGER NOT NULL REFERENCES product_variant (variant_id) ON DELETE RESTRICT,
    quantity   INTEGER NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    line_total NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (order_id, variant_id),
    CONSTRAINT ck_line_qty CHECK (quantity > 0),
    CONSTRAINT ck_line_price CHECK (unit_price > 0),
    CONSTRAINT ck_line_total CHECK (line_total = quantity * unit_price)
);

CREATE TABLE order_promotion (
    order_id         INTEGER NOT NULL REFERENCES customer_order (order_id) ON DELETE CASCADE,
    promotion_id     INTEGER NOT NULL REFERENCES promotion (promotion_id) ON DELETE RESTRICT,
    discount_applied NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (order_id, promotion_id),
    CONSTRAINT ck_op_discount CHECK (discount_applied >= 0)
);

CREATE TABLE payment (
    payment_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     INTEGER NOT NULL REFERENCES customer_order (order_id) ON DELETE CASCADE,
    provider     VARCHAR(30) NOT NULL,
    method       VARCHAR(30) NOT NULL,
    amount       NUMERIC(12, 2) NOT NULL,
    status       VARCHAR(16) NOT NULL,
    provider_ref VARCHAR(60),
    created_at   TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_status CHECK (
        status IN ('pending', 'authorised', 'paid', 'failed', 'refunded')
    )
);

CREATE TABLE shipment (
    shipment_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        INTEGER NOT NULL REFERENCES customer_order (order_id) ON DELETE CASCADE,
    carrier         VARCHAR(40) NOT NULL,
    tracking_number VARCHAR(60),
    status          VARCHAR(16) NOT NULL,
    dispatched_at   TIMESTAMPTZ,
    delivered_at    TIMESTAMPTZ,
    CONSTRAINT ck_shipment_status CHECK (
        status IN ('pending', 'dispatched', 'in_transit', 'delivered', 'returned')
    ),
    CONSTRAINT ck_shipment_dates CHECK (
        delivered_at IS NULL OR dispatched_at IS NULL OR delivered_at >= dispatched_at
    )
);

-- Which lines went in which parcel: supports split shipments.
CREATE TABLE shipment_line (
    shipment_id INTEGER NOT NULL REFERENCES shipment (shipment_id) ON DELETE CASCADE,
    order_id    INTEGER NOT NULL,
    variant_id  INTEGER NOT NULL,
    quantity    INTEGER NOT NULL,
    PRIMARY KEY (shipment_id, order_id, variant_id),
    FOREIGN KEY (order_id, variant_id)
        REFERENCES order_line (order_id, variant_id) ON DELETE CASCADE,
    CONSTRAINT ck_shipment_line_qty CHECK (quantity > 0)
);

-- Append-only inventory ledger. Every sale, restock, return and adjustment is a
-- row, so stock_level.quantity is always reconstructable from this table.
CREATE TABLE stock_movement (
    movement_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id    INTEGER NOT NULL REFERENCES product_variant (variant_id) ON DELETE CASCADE,
    warehouse_id  INTEGER NOT NULL REFERENCES warehouse (warehouse_id) ON DELETE RESTRICT,
    delta         INTEGER NOT NULL,
    reason        VARCHAR(24) NOT NULL,
    ref_order_id  INTEGER REFERENCES customer_order (order_id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_movement_delta CHECK (delta <> 0),
    CONSTRAINT ck_movement_reason CHECK (
        reason IN ('restock', 'sale', 'return', 'adjustment', 'damage')
    ),
    CONSTRAINT ck_movement_sale_ref CHECK (reason <> 'sale' OR ref_order_id IS NOT NULL)
);


-- -----------------------------------------------------------------------------
-- 6. After-sales
-- -----------------------------------------------------------------------------

CREATE TABLE review (
    review_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customer (customer_id) ON DELETE CASCADE,
    product_id  INTEGER NOT NULL REFERENCES product (product_id) ON DELETE CASCADE,
    rating      SMALLINT NOT NULL,
    title       VARCHAR(160),
    body        TEXT,
    created_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT uq_review_customer_product UNIQUE (customer_id, product_id)
);

CREATE TABLE return_request (
    return_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      INTEGER NOT NULL,
    variant_id    INTEGER NOT NULL,
    quantity      INTEGER NOT NULL,
    reason        VARCHAR(40) NOT NULL,
    status        VARCHAR(16) NOT NULL,
    refund_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ NOT NULL,
    FOREIGN KEY (order_id, variant_id)
        REFERENCES order_line (order_id, variant_id) ON DELETE CASCADE,
    CONSTRAINT ck_return_qty CHECK (quantity > 0),
    CONSTRAINT ck_return_refund CHECK (refund_amount >= 0),
    CONSTRAINT ck_return_status CHECK (
        status IN ('requested', 'approved', 'received', 'refunded', 'rejected')
    )
);


-- -----------------------------------------------------------------------------
-- 7. Reconciliation view
--
-- Exposes stored order totals next to values recomputed from order_line. Used in
-- Portfolio 1 to justify the deliberate denormalisation of subtotal and
-- grand_total, and in Portfolio 2 as a query-planning example.
-- -----------------------------------------------------------------------------

CREATE VIEW v_order_reconciliation AS
SELECT o.order_id,
       o.subtotal,
       COALESCE(SUM(l.line_total), 0) AS recomputed_subtotal,
       o.discount_total,
       o.shipping_total,
       o.tax_total,
       o.grand_total,
       COALESCE(SUM(l.line_total), 0) - o.discount_total
           + o.shipping_total + o.tax_total AS recomputed_grand_total
FROM customer_order o
LEFT JOIN order_line l ON l.order_id = o.order_id
GROUP BY o.order_id;

COMMIT;
